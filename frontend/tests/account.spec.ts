import { test, expect } from '@playwright/test';

test('administrator invitation, one-use acceptance and password change work in distinct portals', async ({ page, browser }) => {
  const username = 'invited.e2e.' + Date.now();
  const password = 'Invitation-UI-Fixture-2026!';
  const nextPassword = 'Changed-UI-Fixture-2026!';
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('http://127.0.0.1:8001/login');
  await page.getByLabel('账号', { exact: true }).fill('admin');
  await page.getByLabel('密码', { exact: true }).fill(process.env.EDUFLOW_DEMO_PASSWORD || 'EduFlow-Demo-2026!');
  await page.getByRole('button', { name: '登录工作台' }).click();
  await expect(page).toHaveURL('http://127.0.0.1:8001/');
  await page.goto('http://127.0.0.1:8001/account');
  await page.getByRole('button', { name: '邀请师生' }).click();
  const invite = page.getByRole('dialog', { name: '邀请新师生' });
  await invite.getByLabel('登录账号').fill(username);
  await invite.getByLabel('姓名', { exact: true }).fill('邀请流程测试学生');
  await invite.getByRole('button', { name: '确 定' }).click();
  const linkDialog = page.getByRole('dialog', { name: '账号链接' });
  const link = await linkDialog.getByRole('textbox', { name: '一次性账号链接' }).inputValue();
  expect(link.startsWith('http://127.0.0.1:8101/accept#')).toBeTruthy();
  await linkDialog.getByRole('button', { name: '已保存，关闭' }).click();
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const student = await context.newPage();
  student.on('pageerror', (error) => errors.push(error.message));
  await student.goto(link);
  await expect(student).toHaveURL('http://127.0.0.1:8101/accept');
  await student.getByLabel('新密码', { exact: true }).fill(password);
  await student.getByRole('button', { name: '确认设置密码' }).click();
  await student.getByRole('link', { name: '返回登录页' }).click();
  await student.getByLabel('账号', { exact: true }).fill(username);
  await student.getByLabel('密码', { exact: true }).fill(password);
  await student.getByRole('button', { name: '登录工作台' }).click();
  await expect(student).toHaveURL('http://127.0.0.1:8101/');
  await student.goto('http://127.0.0.1:8101/account');
  await student.getByLabel('原密码', { exact: true }).fill(password);
  await student.getByLabel('新密码', { exact: true }).fill(nextPassword);
  await student.getByRole('button', { name: '保存并撤销旧会话' }).click();
  await expect(student).toHaveURL('http://127.0.0.1:8101/login');
  await student.getByLabel('账号', { exact: true }).fill(username);
  await student.getByLabel('密码', { exact: true }).fill(nextPassword);
  await student.getByRole('button', { name: '登录工作台' }).click();
  await expect(student).toHaveURL('http://127.0.0.1:8101/');
  await student.goto(link);
  await student.getByLabel('新密码', { exact: true }).fill(password);
  await student.getByRole('button', { name: '确认设置密码' }).click();
  await expect(student.getByText(/邀请或重置链接无效|已使用|已失效/)).toBeVisible();
  await context.close();
  expect(errors).toEqual([]);
});
